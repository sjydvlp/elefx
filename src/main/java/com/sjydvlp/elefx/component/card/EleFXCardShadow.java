package com.sjydvlp.elefx.component.card;

/** Controls when an {@link EleFXCard} displays its elevation shadow. */
public enum EleFXCardShadow {
    /** The shadow is continuously visible. */
    ALWAYS,
    /** The shadow is visible while the pointer is over the card. */
    HOVER,
    /** The card has no elevation shadow. */
    NEVER
}
